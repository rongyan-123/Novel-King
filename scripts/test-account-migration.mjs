import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { DatabaseSync } from 'node:sqlite';
import { AccountStore } from '../accounts/store.mjs';
import { migrateAdminData } from '../accounts/migration.mjs';
test('旧数据快照迁给管理员，原件与原库不动，重跑不会覆盖管理员的新数据', async () => {
  const root = mkdtempSync(`${tmpdir()}/novel-migration-test-`);
  const source = root + '/legacy'; mkdirSync(source);
  const db = new DatabaseSync(source + '/novel.db');
  db.exec("PRAGMA journal_mode=WAL; CREATE TABLE fixture(value TEXT); INSERT INTO fixture VALUES('原稿');");
  mkdirSync(source + '/file-library'); writeFileSync(source + '/file-library/original.txt', '原始设定');
  const accounts = new AccountStore(root + '/accounts');
  await accounts.bootstrap('owner', 'fixture-password-2026');
  const owner = accounts.db.prepare("SELECT id FROM users WHERE role='admin'").get();
  const migrated = await migrateAdminData(accounts, source);
  assert.equal(migrated.migrated, true);
  const target = `${accounts.root}/users/${owner.id}`;
  const copy = new DatabaseSync(target + '/novel.db');
  assert.equal(copy.prepare('SELECT value FROM fixture').get().value, '原稿');
  assert.equal(readFileSync(target + '/file-library/original.txt', 'utf8'), '原始设定');
  copy.exec("UPDATE fixture SET value='新的稿子'"); copy.close();
  assert.equal((await migrateAdminData(accounts, source)).migrated, false);
  const checked = new DatabaseSync(target + '/novel.db');
  assert.equal(checked.prepare('SELECT value FROM fixture').get().value, '新的稿子'); checked.close();
  assert.equal(db.prepare('SELECT value FROM fixture').get().value, '原稿');
  assert.ok(existsSync(source + '/novel.db')); db.close(); accounts.close();
});
